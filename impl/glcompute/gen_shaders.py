#!/usr/bin/env python3
"""Generate gl_shaders.h from shaders/*.comp.

    impl/glcompute/gen_shaders.py

The .comp files are the source. The C host embeds them as string literals so
its binary stays self-contained; the Python host (impl/pygl) reads the same
files at run time. That is what makes "class G does not measure the language"
a checkable claim rather than an assertion -- both hosts print the FNV hash of
the shader source they compiled, and the harness compares them.

Same arrangement as spec/tools/gen_dirtable.py: one source of truth, generated
per-language artefacts, and the generated file committed so a build needs no
Python.
"""

from __future__ import annotations

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SHADERS = HERE / "shaders"

HEADER = '''/* GLSL 4.3 compute kernels -- the SPEC-1 tick, one shader per pass.
 *
 * GENERATED by gen_shaders.py from the shaders/ directory.
 * Do not edit by hand -- edit the .comp files and re-run the generator.
 *
 * `precise` is what keeps this bit-exact: it forbids the driver from
 * reassociating and from fusing a multiply and an add into one rounding.
 *
 * It is needed in more places than the obvious one. Marking only the
 * diffusion accumulator was not enough: `x + cos*step` in the agent pass gets
 * fused too, which moves an agent by an ULP and eventually sends it the other
 * way at a sensor comparison. Mesa's llvmpipe happened not to fuse and was
 * exact; the D3D12/NVIDIA path fused and diverged in the *agent* hash, which
 * is what pointed at the agent pass rather than the stencil.
 *
 * Deposits use `atomicAdd` on a uint counter rather than on a float. Integer
 * addition is exact and order-independent, so the count is deterministic no
 * matter how the invocations interleave; the multiply by `deposit` happens
 * once, in the merge pass. Same trick as the CUDA target, same caveat: it
 * reproduces the serial chain only while k*deposit stays exactly representable.
 *
 * Work groups are dispatched as a 2D grid. A 1D dispatch is limited to
 * GL_MAX_COMPUTE_WORK_GROUP_COUNT, which the spec puts at only 65 535 -- the
 * diffusion pass needs 65 536 groups at `medium` and 1 048 576 at `huge`.
 * Exceeding it is not an error the driver reports; the dispatch silently does
 * nothing. Every shader rebuilds its linear index from x and y.
 */
#ifndef SB_GL_SHADERS_H
#define SB_GL_SHADERS_H

'''

FNV_OFFSET = 0x811C9DC5
FNV_PRIME = 0x01000193


def fnv32(data: bytes) -> int:
    """SB-FNV32 over bytes -- the same construction as SPEC-1 section 6, used
    here so both hosts can prove they compiled identical source."""
    h = FNV_OFFSET
    for b in data:
        h = ((h ^ b) * FNV_PRIME) & 0xFFFFFFFF
    return h


def c_literal(text: str, indent: str = "    ") -> str:
    out = []
    for line in text.split("\n"):
        if not line and line is text.split("\n")[-1]:
            continue
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'{indent}"{esc}\\n"')
    return "\n".join(out)


def main() -> int:
    common = (SHADERS / "common.glsl").read_text(encoding="utf-8")
    parts = {n: (SHADERS / f"{n}.comp").read_text(encoding="utf-8")
             for n in ("agents", "merge", "diffuse")}

    body = [HEADER]
    body.append("#define SB_GLSL_COMMON \\\n"
                + " \\\n".join(c_literal(common).split("\n")) + "\n\n")

    for name, text in parts.items():
        body.append(f"static const char *SB_GLSL_{name.upper()} =\n"
                    f"    SB_GLSL_COMMON\n{c_literal(text)};\n\n")

    # The hash covers exactly what a host compiles: common + the pass body,
    # for each of the three passes, in order.
    blob = b"".join((common + parts[n]).encode("utf-8")
                    for n in ("agents", "merge", "diffuse"))
    body.append("/* FNV-32 of common.glsl + each pass, in agents/merge/diffuse\n"
                " * order. Both hosts print this so a mismatch is visible rather\n"
                " * than silently comparing two different shaders. */\n"
                f"#define SB_GLSL_HASH 0x{fnv32(blob):08X}u\n\n")
    body.append("#endif /* SB_GL_SHADERS_H */\n")

    dst = HERE / "gl_shaders.h"
    dst.write_text("".join(body), encoding="utf-8", newline="\n")
    print(f"wrote {dst.relative_to(HERE.parent.parent)}  shader hash 0x{fnv32(blob):08X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
